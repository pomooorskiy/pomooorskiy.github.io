(function () {
  const nameInput = document.getElementById('partbiletName');
  const photoInput = document.getElementById('partbiletPhoto');
  const btn = document.getElementById('partbiletBtn');
  const card = document.getElementById('partbiletCard');
  const photoPreview = document.getElementById('partbiletPhotoPreview');
  const fioEl = document.getElementById('partbiletFio');
  const numberEl = document.getElementById('partbiletNumber');
  const dateEl = document.getElementById('partbiletDate');
  const downloadBtn = document.getElementById('partbiletDownload');
  if (!nameInput || !btn || !card) return;

  let photoDataUrl = null;

  // Загрузка фото
  if (photoInput) {
    photoInput.addEventListener('change', (e) => {
      const file = e.target.files[0];
      if (!file) return;
      const reader = new FileReader();
      reader.onload = (ev) => {
        photoDataUrl = ev.target.result;
      };
      reader.readAsDataURL(file);
    });
  }

  function randomNumber() {
    const n = Math.floor(Math.random() * 9000) + 1000;
    return 'ППП-2026-' + n;
  }

  function formatDate(d) {
    const dd = String(d.getDate()).padStart(2, '0');
    const mm = String(d.getMonth() + 1).padStart(2, '0');
    const yyyy = d.getFullYear();
    return `${dd}.${mm}.${yyyy}`;
  }

  btn.addEventListener('click', () => {
    const fio = nameInput.value.trim();
    if (!fio) {
      nameInput.focus();
      nameInput.style.borderColor = '#e74c3c';
      setTimeout(() => { nameInput.style.borderColor = ''; }, 1500);
      return;
    }

    // Заполняем карточку
    fioEl.textContent = fio;
    numberEl.textContent = randomNumber();
    dateEl.textContent = formatDate(new Date());

    if (photoDataUrl) {
      photoPreview.src = photoDataUrl;
    } else {
      // Если фото не загружено — используем логотип
      photoPreview.src = 'https://lh3.googleusercontent.com/d/1KRb9pi-oAD3qofva0diEfKu99MLGGNY4';
    }

    card.style.display = 'flex';
    if (downloadBtn) downloadBtn.style.display = 'inline-block';

    // Плавное появление
    card.style.opacity = '0';
    card.style.transform = 'scale(0.9)';
    setTimeout(() => {
      card.style.transition = 'opacity 0.4s ease, transform 0.4s ease';
      card.style.opacity = '1';
      card.style.transform = 'scale(1)';
    }, 50);
  });

  // Скачивание
  if (downloadBtn && typeof html2canvas !== 'undefined') {
    downloadBtn.addEventListener('click', () => {
      html2canvas(card, {
        backgroundColor: null,
        scale: 2,
        useCORS: true
      }).then(canvas => {
        const link = document.createElement('a');
        const fio = nameInput.value.trim().replace(/\s+/g, '_') || 'partbilet';
        link.download = `partbilet_${fio}.png`;
        link.href = canvas.toDataURL('image/png');
        link.click();
      }).catch(err => {
        console.error('Ошибка скачивания:', err);
        alert('Не удалось скачать билет. Попробуйте ещё раз.');
      });
    });
  }
})();